// Turns the default-language content plus ai-notes.md into compact plain text
// for the AI (plain text uses fewer tokens than JSON) and writes it to
// worker/generated/context.ts, which is git-ignored. Case studies and the
// notes/ topics are written separately, to be searched per question.
// Runs before dev, build and deploy. Run: npm run ai-context

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ContentError, loadContent } from "../src/content/load.ts";

let content;
try {
  content = loadContent();
} catch (err) {
  if (!(err instanceof ContentError)) throw err;
  console.error(`\n${err.message}\n`);
  process.exit(1);
}

const { site } = content;
const l = content.locales[site.defaultLanguage]!;
const firstName = site.firstName ?? site.name.split(/\s+/)[0];
const plain = (s: string) => s.replaceAll("**", "");
const ym = (s: string | null) => s ?? "present";
const lines: string[] = [];
const section = (title: string) => lines.push("", `## ${title}`);

lines.push(`# ${site.name}`, `Title: ${l.hero.title}`, `Email: ${site.email}`);
if (site.linkedin) lines.push(`LinkedIn: ${site.linkedin}`);
if (site.github) lines.push(`GitHub: ${site.github}`);
if (l.contact.location) lines.push(`Location: ${l.contact.location}`);
if (l.contact.workStatus) lines.push(`Work status: ${l.contact.workStatus}`);
if (l.hero.tags.length) lines.push(`Open to: ${l.hero.tags.map((t) => t.text).join("; ")}`);

if (l.hero.paragraphs.length) {
  section("Summary");
  lines.push(...l.hero.paragraphs.map(plain));
}

if (l.experience.length) {
  section("Experience (newest first)");
  for (const j of l.experience) {
    lines.push(`- ${j.role}, ${j.company}${j.about ? ` (${j.about})` : ""}, ${j.start} to ${ym(j.end)}`);
    lines.push(...j.bullets.map((b) => `  * ${b}`));
  }
}

if (l.highlights.length) {
  section("Key highlights");
  for (const h of l.highlights) lines.push(`- ${h.title} [${h.tag}]: ${h.text}`);
}

// Case studies are long, so like the notes they're searched per question
// rather than sent every time. Each one becomes a single topic.
// The title names the employer (the first one the case mentions), so a question
// like "What did you do at <company>?" finds that company's case study.
const employers = l.experience.map((j) => j.company.split(",")[0].replace(/\s+(Corp|Inc|Ltd|LLC|AB)\.?$/i, "").trim());
const caseStudies = l.highlights.flatMap((h) => {
  if (!h.caseStudy) return [];
  const { facts, blocks } = h.caseStudy;
  const body = [h.text];
  if (facts.length) body.push(facts.map((f) => `${f.label}: ${f.value}`).join("; "));
  body.push(...blocks.map((b) => `${b.heading}: ${b.items.join(" ")}`));
  const text = body.join("\n");
  const employer = employers
    .map((name) => ({ name, at: text.indexOf(name) }))
    .filter((e) => e.at >= 0)
    .sort((a, b) => a.at - b.at)[0]?.name;
  return [{ title: `Case study: ${h.title} [${h.tag}]${employer ? `, at ${employer}` : ""}`, text }];
});

const { featured, groups } = l.skills;
if (featured?.items.length || groups.length) {
  section("Skills");
  if (featured?.items.length) lines.push(`- ${featured.label}: ${featured.items.join("; ")}`);
  for (const g of groups) lines.push(`- ${g.label}: ${g.items.join("; ")}`);
}

const { degrees, certifications } = l.education;
if (degrees.length || certifications.length) {
  section("Education");
  for (const d of degrees) lines.push(`- ${d.title}, ${d.org}`);
  for (const c of certifications) lines.push(`- Certificate: ${c.title}, ${c.org}${c.year ? `, ${c.year}` : ""}`);
}

if (l.languages.length) {
  section("Languages");
  for (const lang of l.languages) {
    const tests = lang.tests.map((t) => `${t.name}${t.result ? ` ${t.result}` : ""}`).join("; ");
    lines.push(`- ${lang.name}: ${lang.level}${tests ? ` (tests: ${tests})` : ""}`);
  }
}

if (l.projects.length) {
  section("Side projects");
  for (const p of l.projects) lines.push(`- ${p.title}: ${p.text}${p.link ? ` (${p.link.label}: ${p.link.url})` : ""}`);
}

if (l.interests.length) {
  section("Personal interests");
  for (const i of l.interests) lines.push(`- ${i.name}: ${i.text}`);
}

if (content.aiNotes?.trim()) {
  section("More notes from me");
  lines.push(content.aiNotes.trim());
}

const text = lines.join("\n").trim() + "\n";
const owner = { name: site.name, firstName, email: site.email };
// Hidden notes and case studies: the Worker searches these per question and sends only the relevant ones.
const notes = [...content.notes.map(({ title, text }) => ({ title, text })), ...caseStudies];

const outDir = join(process.cwd(), "worker", "generated");
mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, "context.ts"),
  [
    "// GENERATED by scripts/build-ai-context.ts from the content folder. Do not edit; git-ignored.",
    `export const OWNER = ${JSON.stringify(owner)};`,
    `export const CONTEXT = ${JSON.stringify(text)};`,
    `export const NOTES: { title: string; text: string }[] = ${JSON.stringify(notes, null, 1)};`,
    "",
  ].join("\n"),
);
const notesTokens = Math.round(notes.reduce((n, t) => n + t.title.length + t.text.length, 0) / 4);
console.log(
  `AI context: ${content.label} (${site.name}), about ${Math.round(text.length / 4)} tokens always sent` +
    (notes.length
      ? `; ${notes.length} topics (${content.notes.length} from notes, ${caseStudies.length} case ${caseStudies.length === 1 ? "study" : "studies"}; about ${notesTokens} tokens) searched per question`
      : ""),
);
