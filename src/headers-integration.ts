// Writes dist/_headers after the build: security headers for every static
// page and file (SPEC §7). Cloudflare applies _headers to static assets only;
// the Worker sets its own headers on /api/* responses.
//
// The Content Security Policy allows only this site plus Cloudflare Turnstile.
// The few inline scripts and styles in the built pages (for example the tiny
// script in <head> that runs before the first paint) are allowed by their
// SHA-256 hashes, computed here from the built files, so the policy always
// matches what was built.

import type { AstroIntegration } from "astro";
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const TURNSTILE = "https://challenges.cloudflare.com";

export function securityHeaders(): AstroIntegration {
  return {
    name: "security-headers",
    hooks: {
      "astro:build:done": ({ dir }) => {
        const out = fileURLToPath(dir);
        const scripts = new Set<string>();
        const styles = new Set<string>();
        for (const file of htmlFiles(out)) {
          const html = readFileSync(file, "utf8");
          for (const m of html.matchAll(/<script(?![^>]*\ssrc=)[^>]*>([\s\S]*?)<\/script>/g)) scripts.add(hash(m[1]));
          for (const m of html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)) styles.add(hash(m[1]));
        }
        const csp = [
          "default-src 'self'",
          `script-src 'self' ${[...scripts].join(" ")} ${TURNSTILE}`,
          `style-src 'self' ${[...styles].join(" ")}`,
          "img-src 'self'",
          "font-src 'self'",
          "connect-src 'self'",
          // 'self' for the certificate pop-up's PDF frame.
          `frame-src 'self' ${TURNSTILE}`,
          "object-src 'none'",
          "base-uri 'self'",
          "form-action 'self'",
          // This site's own pages may frame its PDFs; nobody else may frame anything.
          "frame-ancestors 'self'",
        ]
          .map((d) => d.replace(/\s+/g, " ").trim())
          .join("; ");
        writeFileSync(
          join(out, "_headers"),
          [
            "# Generated by src/headers-integration.ts at build time. Do not edit.",
            "/*",
            `  Content-Security-Policy: ${csp}`,
            "  X-Content-Type-Options: nosniff",
            "  Referrer-Policy: strict-origin-when-cross-origin",
            "  X-Frame-Options: SAMEORIGIN",
            "  Permissions-Policy: camera=(), microphone=(), geolocation=()",
            "",
          ].join("\n"),
        );
      },
    },
  };
}

function hash(content: string): string {
  return `'sha256-${createHash("sha256").update(content, "utf8").digest("base64")}'`;
}

function htmlFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? htmlFiles(join(dir, e.name)) : e.name.endsWith(".html") ? [join(dir, e.name)] : [],
  );
}
